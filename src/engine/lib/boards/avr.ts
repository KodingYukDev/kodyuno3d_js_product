/** A0…An aliases plus LED_BUILTIN, injected into the interpreter scope. */
function avrAliases(pins: BoardPin[], led: number): Record<string, number | string> {
  const aliases: Record<string, number | string> = { LED_BUILTIN: led }
  for (const pin of pins) {
    if (pin.adc) aliases[pin.adc] = pin.id
  }
  return aliases
}

